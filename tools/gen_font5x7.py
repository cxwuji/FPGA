lines.append('')
lines.append('// 5x7 点阵字库（由 tools/gen_font5x7.py 生成，不要手改）。按 ASCII 索引，表里没有的字符是空白。')
lines.append('// bits[4] 是最左边一列。组合逻辑，查表一拍内出结果。')
lines.append('module font5x7_rom (')
lines.append('    input  wire [6:0] ch,')
lines.append('    input  wire [2:0] row,')
lines.append('    output reg  [4:0] bits')
lines.append(');')
lines.append('    always @* begin')
lines.append('        case ({ch, row})')
for c in sorted(FONT, key=ord):
    rows = FONT[c]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
    if c == ' ':
        continue
    for r, v in enumerate(rows):
        if v == '00000':
            continue
        lines.append("            {7'd%d, 3'd%d}: bits = 5'b%s;   // '%s'" % (ord(c), r, v, c))
lines.append("            default: bits = 5'b00000;")
lines.append('        endcase')
lines.append('    end')
lines.append('endmodule')

